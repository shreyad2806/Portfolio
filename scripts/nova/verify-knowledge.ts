/**
 * Knowledge audit + human-verification report — `npm run nova:verify`.
 * Writes docs/nova/human-verification-report.md from nova-knowledge/ (documents, faq.json, verification.json, index.json).
 * `--check` exits 1 when the committed report is out of date.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { internalNotes, parseDocument } from "../../lib/nova/knowledge/parse";
import { tokens } from "../../lib/nova/knowledge/text";
import type { VerificationRecord } from "../../lib/nova/knowledge/verification";
import { PROJECTS } from "../../lib/nova/tools/registry";
import type { IndexFile } from "../../lib/nova/types";

const root = path.resolve(__dirname, "../..");
const kdir = path.join(root, "nova-knowledge");
const out = path.join(root, "docs/nova/human-verification-report.md");

const walk = (d: string, acc: string[] = []): string[] => {
  for (const n of readdirSync(d)) { const p = path.join(d, n); if (statSync(p).isDirectory()) walk(p, acc); else if (n.endsWith(".md") && n !== "README.md") acc.push(p); }
  return acc;
};
const docs = walk(kdir).map((f) => parseDocument(readFileSync(f, "utf8"), path.relative(kdir, f).split(path.sep).join("/")));
const ver = JSON.parse(readFileSync(path.join(kdir, "verification.json"), "utf8")) as { records: VerificationRecord[] };
const faq = JSON.parse(readFileSync(path.join(kdir, "faq.json"), "utf8")) as { faqs: { id: string; sources: string[]; answer: string }[] };
const index = JSON.parse(readFileSync(path.join(kdir, "index.json"), "utf8")) as IndexFile;

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const L: string[] = [];
const by = (st: string) => ver.records.filter((r) => r.status === st);

L.push("# Nova human-verification report", "",
  "_Generated by `npm run nova:verify` from `nova-knowledge/verification.json` and the knowledge documents. Do not edit by hand — edit the records and re-run._", "",
  "**Verification policy** (enforced in code and tested):",
  "1. `TODO(human)` text is never indexed, embedded or shown (internal notes live in a `Verification notes (internal)` section that the chunker skips).",
  "2. Unverified documents are never evidence — retrieval excludes them; a matching one only produces a controlled abstention that says a note exists but is not verified.",
  "3. Conflicting facts are never merged silently: the answer states the approved (resume) version and discloses the conflict via the record's `public_note`.",
  "4. Source preference: approved resume → portfolio data → owner-confirmed records.",
  "5. Insufficient evidence → controlled abstention (no guessing).", "",
  "Nothing below has been resolved on Shreya's behalf. Where Nova must pick a version, it picks the resume and says so.", "");

L.push("## Summary", "", `| | |\n|---|---|\n| Documents | ${docs.length} (${docs.filter((d) => d.verified).length} verified, ${docs.filter((d) => !d.verified).length} unverified) |\n| Indexed chunks | ${index.chunks.length} (unverified chunks are kept for the report but excluded from retrieval) |\n| Conflicts | ${by("conflict").length} |\n| Unverified facts | ${by("unverified").length} |\n| Needs human input | ${by("needs-human").length} |`, "");

const table = (rs: VerificationRecord[]) => {
  L.push("| ID | Topic | What is wrong / unknown | Sources | What Nova does now | What a human must do |", "|---|---|---|---|---|---|");
  for (const r of rs) L.push(`| \`${r.id}\` | ${esc(r.topic)} | ${esc(r.statement)} | ${esc(r.sources.join("; "))} | ${esc(r.nova_behavior)} | ${esc(r.action_for_human)} |`);
  L.push("");
};
for (const [st, title] of [["conflict", "Conflicting facts"], ["unverified", "Unverified claims"], ["needs-human", "Missing or unconfirmed information"]] as const) {
  L.push(`## ${title}`, ""); table(by(st));
}

L.push("## Documents by verification status", "", "| Document | Verified | Source | Internal notes |", "|---|---|---|---|");
for (const d of docs.sort((a, b) => a.source_path.localeCompare(b.source_path))) {
  const n = internalNotes(d);
  L.push(`| \`${d.source_path}\` | ${d.verified ? "yes" : "**no**"} | ${esc(d.source)} | ${n.notes.length} note(s)${n.todos.length ? `, **${n.todos.length} TODO(human) in public text**` : ""} |`);
}
L.push("");

// ---- Audit: duplicates, missing links, FAQ drift.
const sets = index.chunks.map((c) => ({ c, s: new Set(tokens(c.text)) }));
const dups: string[] = [];
for (let i = 0; i < sets.length; i++) for (let j = i + 1; j < sets.length; j++) {
  if (sets[i].c.document_id === sets[j].c.document_id) continue;
  const a = sets[i].s, b = sets[j].s; if (a.size < 12 || b.size < 12) continue;
  let inter = 0; for (const t of a) if (b.has(t)) inter++;
  const sim = inter / (a.size + b.size - inter);
  if (sim >= 0.6) dups.push(`\`${sets[i].c.chunk_id}\` ≈ \`${sets[j].c.chunk_id}\` (${(sim * 100).toFixed(0)}% overlap)`);
}
L.push("## Audit findings", "", "### Near-duplicate knowledge (different documents, ≥60% token overlap)", "", dups.length ? dups.map((d) => `- ${d}`).join("\n") : "None found.", "");

const noLink: string[] = [];
for (const d of docs.filter((x) => x.category === "projects")) {
  const id = d.document_id.slice("projects-".length);
  const p = PROJECTS.find((x) => x.id === id);
  if (!p) { noLink.push(`\`${d.source_path}\` — not in the project registry, so Nova cannot link it`); continue; }
  if (!p.hasCaseStudy && !p.github) noLink.push(`\`${d.source_path}\` — no case-study page and no GitHub link`);
  else if (!p.hasCaseStudy) noLink.push(`\`${d.source_path}\` — no case-study page; sources link to GitHub`);
}
for (const d of docs.filter((x) => ["experience", "education", "achievements", "skills"].includes(x.category))) noLink.push(`\`${d.source_path}\` — no dedicated page; sources link to a section (${d.category === "experience" || d.category === "achievements" ? "Journey" : "home"})`);
L.push("### Source links", "", noLink.map((x) => `- ${x}`).join("\n"), "");

const faqIssues: string[] = [];
for (const f of faq.faqs) for (const sp of f.sources) { const d = docs.find((x) => x.source_path === sp); if (!d) faqIssues.push(`FAQ \`${f.id}\` cites missing \`${sp}\``); else if (!d.verified) faqIssues.push(`FAQ \`${f.id}\` cites unverified \`${sp}\``); }
L.push("### FAQ consistency", "", faqIssues.length ? faqIssues.map((x) => `- ${x}`).join("\n") : `All ${faq.faqs.length} FAQ answers cite existing, verified documents. FAQ text is hand-written and duplicates document facts, so edit both together (checked by \`nova:ingest:check\`).`, "");

L.push("### Outdated information", "",
  "- `public/SDE.pdf` (served as the resume download) is an older resume with a personal phone number — see record `public-sde-pdf`.",
  "- `data/experience.ts` carries years that disagree with the resume — see `et-genai-year`, `edu-dates`, `lawgpt-title`.", "");

const text = L.join("\n");
if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== text) { console.error("human-verification-report.md is stale — run `npm run nova:verify`."); process.exit(1); }
  console.log("report up to date");
} else { writeFileSync(out, text); console.log(`wrote ${path.relative(root, out)} — ${ver.records.length} records, ${dups.length} near-duplicate pairs`); }
